#!/usr/bin/env bash
# Regenerates Packaging/homebrew/rightcmd-formula.rb for a release: a Homebrew *formula*
# that builds RightCmd from the tagged source and assembles an ad-hoc-signed .app.
#
# Usage: scripts/update-formula.sh <github-owner/repo>
#   The version is read from Packaging/Info.plist; the tag <version> and its GitHub
#   source tarball must already exist (the SHA-256 is computed from the download). Tags
#   are the bare version by default; set TAG_PREFIX=v if you tag as v<version>.
#
#   TAP=you/tap scripts/update-formula.sh you/RightCmd
#   also copies the formula into the local tap as Formula/rightcmd.rb and audits it.
#
# Why a formula as well as a cask: a locally built binary is never quarantined, so it
# needs no Developer ID to pass Gatekeeper. The cost is that an ad-hoc signature changes
# on every build, so macOS drops the Accessibility grant after each upgrade.
set -euo pipefail
cd "$(dirname "$0")/.."

REPO="${1:?github owner/repo, e.g. zi/RightCmd}"
VERSION="$(/usr/libexec/PlistBuddy -c "Print :CFBundleShortVersionString" Packaging/Info.plist)"
TAG_PREFIX="${TAG_PREFIX:-}"
TARBALL_URL="https://github.com/$REPO/archive/refs/tags/${TAG_PREFIX}$VERSION.tar.gz"
OUT="Packaging/homebrew/rightcmd-formula.rb"

echo "==> Fetching $TARBALL_URL to compute its checksum"
TMP="$(mktemp)"
curl -fsSL "$TARBALL_URL" -o "$TMP" || { echo "error: tag ${TAG_PREFIX}$VERSION is not published on GitHub yet" >&2; exit 1; }
SHA="$(shasum -a 256 "$TMP" | awk '{print $1}')"
rm -f "$TMP"

cat > "$OUT" << FORMULA
# Builds RightCmd from source and installs an ad-hoc-signed RightCmd.app into the
# Homebrew prefix. Generated by scripts/update-formula.sh; do not edit by hand.
class Rightcmd < Formula
  desc "Hold right ⌘ and type the first letters of an app to switch to it"
  homepage "https://github.com/$REPO"
  url "$TARBALL_URL"
  sha256 "$SHA"
  license "MIT"
  head "https://github.com/$REPO.git", branch: "main"

  depends_on :macos
  depends_on macos: :tahoe
  depends_on xcode: ["26.0", :build]

  def install
    # --disable-sandbox turns off SwiftPM's own sandbox, which conflicts with Homebrew's.
    system "swift", "build", "-c", "release", "--disable-sandbox"
    bin_path = Utils.safe_popen_read("swift", "build", "-c", "release", "--disable-sandbox", "--show-bin-path").strip

    app = prefix/"RightCmd.app"
    (app/"Contents/MacOS").mkpath
    (app/"Contents/Resources").mkpath
    cp "#{bin_path}/RightCmd", app/"Contents/MacOS/RightCmd"
    cp "Packaging/Info.plist", app/"Contents/Info.plist"
    cp "Packaging/AppIcon.icns", app/"Contents/Resources/AppIcon.icns"
    (app/"Contents/PkgInfo").write "APPL????"
    system "/usr/libexec/PlistBuddy", "-c", "Add :CFBundleIconFile string AppIcon", app/"Contents/Info.plist"
    system "codesign", "--force", "--sign", "-", app

    # \`rightcmd\` on the command line launches (or re-launches) the app.
    (bin/"rightcmd").write <<~SH
      #!/bin/sh
      exec open "#{opt_prefix}/RightCmd.app" "\\$@"
    SH
  end

  def caveats
    <<~EOS
      RightCmd.app was built on this Mac and ad-hoc signed, so Gatekeeper allows it.
      It lives at:
        #{opt_prefix}/RightCmd.app
      Launch it with \`rightcmd\`, or copy it to /Applications so Spotlight and
      Login Items can find it:
        cp -R #{opt_prefix}/RightCmd.app /Applications/

      It needs Accessibility access (System Settings › Privacy & Security ›
      Accessibility). Because the signature is ad-hoc, macOS forgets that grant
      whenever the binary changes: after \`brew upgrade rightcmd\`, remove RightCmd
      from the Accessibility list and add it again. A Developer ID-signed build
      (the cask) does not have this limitation.
    EOS
  end

  test do
    assert_predicate prefix/"RightCmd.app/Contents/MacOS/RightCmd", :executable?
    system "codesign", "--verify", prefix/"RightCmd.app"
    assert_match "RightCmd", shell_output("/usr/libexec/PlistBuddy -c 'Print :CFBundleName' #{prefix}/RightCmd.app/Contents/Info.plist")
  end
end
FORMULA

echo "wrote $OUT (version $VERSION, sha256 $SHA)"

if [[ -n "${TAP:-}" ]]; then
    OWNER="${TAP%%/*}"
    NAME="${TAP##*/}"
    TAP_DIR="$(brew --repository)/Library/Taps/$OWNER/homebrew-$NAME"
    if [[ ! -d "$TAP_DIR" ]]; then
        echo "==> Creating local tap $TAP"
        brew tap-new "$TAP" --no-git >/dev/null
    fi
    mkdir -p "$TAP_DIR/Formula"
    cp "$OUT" "$TAP_DIR/Formula/rightcmd.rb"
    echo "==> Installed into $TAP_DIR/Formula/rightcmd.rb"
    echo "==> brew audit --strict --formula $TAP/rightcmd"
    brew audit --strict --formula "$TAP/rightcmd"
    echo "==> brew style $TAP"
    brew style "$TAP"
    echo "==> OK. Build and install locally with: brew install --build-from-source $TAP/rightcmd"
    echo "    Then commit and push $TAP_DIR to github.com/$OWNER/homebrew-$NAME."
else
    echo "next: TAP=you/tap scripts/update-formula.sh $REPO   # copy into a local tap and audit it"
fi
